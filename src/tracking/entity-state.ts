/** Supported values for entity state. */ export enum EntityState {
    /** Select the detached behavior. */ Detached = 'Detached',
    /** Select the unchanged behavior. */ Unchanged = 'Unchanged',
    /** Select the added behavior. */ Added = 'Added',
    /** Select the modified behavior. */ Modified = 'Modified',
    /** Select the deleted behavior. */ Deleted = 'Deleted',
}
